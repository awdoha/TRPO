namespace Lab3;

/// <summary>
/// Панель для рисования с включённой двойной буферизацией.
/// SetStyle доступен только изнутри Control, поэтому обычный Panel
/// для этого требует собственного наследника.
/// </summary>
// sealed — от класса нельзя наследоваться. Используется: MainForm создаёт его в конструкторе
// (new DrawingPanel { Dock = Fill ... }) как область рисования; на нём срабатывают Paint и события мыши.
public sealed class DrawingPanel : Panel
{
    // Конструктор. Используется: вызывается при new DrawingPanel() в конструкторе MainForm.
    public DrawingPanel()
    {
        // Двойная буферизация простыми словами: фигура сначала рисуется в невидимую картинку в памяти,
        // и только готовый кадр целиком показывается на экране, поэтому при движении точек нет мерцания.
        // SetStyle — protected-метод Control, поэтому снаружи его не вызвать: нужен наследник.
        SetStyle(
            // Не стирать фон отдельно от рисования — всё делается в одном проходе WM_PAINT (меньше мерцания).
            ControlStyles.AllPaintingInWmPaint |
            // Отрисовку берёт на себя код (событие Paint в MainForm.DrawPanel_Paint).
            ControlStyles.UserPaint |
            // Собственно двойная буферизация: рисование идёт в буфер, потом кадр копируется на экран.
            ControlStyles.OptimizedDoubleBuffer,
            // true — включить перечисленные стили (false выключил бы).
            true);
    } // конец конструктора DrawingPanel
} // конец класса DrawingPanel
